const tables: Record<string, Table> = { en, es, pt, fr, de, it, ar, he, iw: he, fa, ru, zh, "zh-hant": zhHant, ja, ko, tr, nl, pl };
let current: Table = en;
let code = "en";
let rules = new Intl.PluralRules("en");
const enRules = rules;

/** Languages written right to left. */
const RTL = /^(ar|he|iw|fa|ur|ps|sd|ug|yi|dv|ckb)$/;

/** "rtl" for a page in a right-to-left language, else nothing (Sift follows the page's own direction). */
export function dirOf(lang: string | undefined): "rtl" | undefined {
  return RTL.test((lang || "").toLowerCase().split(/[-_]/)[0]) ? "rtl" : undefined;
}

export function setLang(lang: string) {
  chosen = true;
  use(lang);
}

/** Until a page is read, the document's own lang attribute: the first labels and search box are in the page's language too. */
let chosen = false;
let guessed: string | undefined;
function guess() {
  const l = typeof document !== "undefined" ? document.documentElement?.lang ?? "" : "";
  if (l !== guessed) use((guessed = l));
}

let usedFor = "";
function use(lang: string) {
  const full = (lang || navigator.language || "en").toLowerCase().replace(/_/g, "-");
  if (full === usedFor) return;
  usedFor = full;
  const base = full.split("-")[0];
  // zh-TW, zh-Hant-HK: the traditional table; other Chinese: simplified.
  const key = base === "zh" && /-(tw|hk|mo|hant)\b/.test(full) ? "zh-hant" : base;
  current = tables[key] ?? en;
  code = tables[key] ? key : "en";
  try {
    rules = new Intl.PluralRules(code === "zh-hant" ? "zh" : code);
  } catch {
    rules = enRules;
  }
}

export function t(k: keyof Strings, vars?: Record<string, string | number>): string {
  if (!chosen) guess();
  // A count picks its form ("1 new item"), in the shown language's rules.
  const n = vars ? Number(vars.n) : NaN;
  const form = (lang: string, r: Intl.PluralRules) => (vars && /^\d+$/.test(String(vars.n ?? "")) ? plurals[lang]?.[k]?.[r.select(n)] : undefined);
  let s = current[k] !== undefined ? form(code, rules) ?? current[k]! : form("en", enRules) ?? en[k];
  if (vars) for (const [n, v] of Object.entries(vars)) s = s.replace("{" + n + "}", String(v));
  return s;
}

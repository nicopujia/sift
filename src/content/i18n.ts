  es: { nSuggestions: { one: "{n} sugerencia" }, newItems: { one: "{n} elemento nuevo" }, nComments: { one: "{n} comentario" }, votes: { one: "{n} voto" }, moreRows: { one: "{n} fila más en la página original." }, moreCols: { one: "Hay {n} columna más al costado. Desplazá la tabla de lado para verla." } },
  pt: { nSuggestions: { one: "{n} sugestão" }, newItems: { one: "{n} item novo" }, nComments: { one: "{n} comentário" }, votes: { one: "{n} voto" }, nLikes: { one: "{n} curtida" }, moreRows: { one: "Mais {n} linha na página original." }, moreCols: { one: "Mais {n} coluna está fora da tela, ao lado. Role a tabela para o lado para vê-la." } },
  ar: { newItems: { one: "عنصر جديد واحد", two: "عنصران جديدان", few: "{n} عناصر جديدة", many: "{n} عنصرًا جديدًا" } },
  nl: { newItems: { one: "{n} nieuw item" } },
